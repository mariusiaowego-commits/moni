CREATE TABLE IF NOT EXISTS enterprises (
    enterprise_id TEXT PRIMARY KEY,
    name_cn       TEXT NOT NULL,
    name_en       TEXT,
    industry_l1   TEXT NOT NULL
        CHECK (industry_l1 IN ('银行', '保险', '证券', '互联网', '其他')),
    industry_l2   TEXT,
    country_code  TEXT,
    parent_id     TEXT,
    status        TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'merged', 'pending_review')),
    created_at    TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at    TEXT NOT NULL DEFAULT (datetime('now')),
    FOREIGN KEY (parent_id) REFERENCES enterprises(enterprise_id)
);

CREATE INDEX IF NOT EXISTS idx_ent_industry ON enterprises(industry_l1, industry_l2);
CREATE INDEX IF NOT EXISTS idx_ent_parent   ON enterprises(parent_id);

CREATE TABLE IF NOT EXISTS enterprise_aliases (
    alias_norm    TEXT PRIMARY KEY,
    alias         TEXT NOT NULL,
    enterprise_id TEXT NOT NULL,
    source_type   TEXT NOT NULL DEFAULT 'seed'
        CHECK (source_type IN ('seed', 'auto_llm', 'manual_user')),
    created_at    TEXT NOT NULL DEFAULT (datetime('now')),
    FOREIGN KEY (enterprise_id) REFERENCES enterprises(enterprise_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ent_alias_ent ON enterprise_aliases(enterprise_id);

CREATE TABLE IF NOT EXISTS case_enterprises (
    case_id       TEXT NOT NULL,
    enterprise_id TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT 'subject'
        CHECK (role IN ('subject', 'counterparty', 'partner', 'vendor', 'investor', 'regulator')),
    raw_name      TEXT,
    source_type   TEXT NOT NULL DEFAULT 'auto_rule'
        CHECK (source_type IN ('auto_rule', 'auto_llm', 'manual_user')),
    created_at    TEXT NOT NULL DEFAULT (datetime('now')),
    PRIMARY KEY (case_id, enterprise_id, role),
    FOREIGN KEY (case_id)       REFERENCES cases(case_id) ON DELETE CASCADE,
    FOREIGN KEY (enterprise_id) REFERENCES enterprises(enterprise_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_case_ent_ent ON case_enterprises(enterprise_id, role);

ALTER TABLE cases ADD COLUMN subject_enterprise_id TEXT;
CREATE INDEX IF NOT EXISTS idx_cases_subject_ent ON cases(subject_enterprise_id);

